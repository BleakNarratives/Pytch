class PitchGenerator:
    """Main pitch generation and distribution engine"""
    
    def __init__(self, project_data: ProjectData, log_file: str = "pattern_journal.json"):
        self.project = project_data
        self.log_file = log_file
        self.templates = PitchTemplate()
        
    def generate_investor_deck(self, output_path: Optional[Path] = None) -> str:
        """Generate investor pitch deck"""
        deck = self.templates.investor_deck(self.project)
        
        if output_path is None:
            output_path = Path(f"{self.project.name.lower().replace(' ', '_')}_pitch_deck.md")
        
        output_path.write_text(deck)
        self.log(f"Generated investor deck: {output_path}")
        
        return deck
    
    def generate_grant_proposal(self, output_path: Optional[Path] = None) -> str:
        """Generate research grant proposal"""
        proposal = self.templates.grant_proposal(self.project)
        
        if output_path is None:
            output_path = Path(f"{self.project.name.lower().replace(' ', '_')}_grant_proposal.md")
        
        output_path.write_text(proposal)
        self.log(f"Generated grant proposal: {output_path}")
        
        return proposal
    
    def generate_email(self, target: PitchTarget) -> str:
        """Generate personalized email based on target type"""
        if target.target_type == "vc" or target.target_type == "angel":
            email = self.templates.cold_email_vc(target, self.project)
        elif target.target_type == "grant":
            email = self.templates.cold_email_grant(target, self.project)
        elif target.target_type == "partner":
            email = self.templates.partnership_pitch(target, self.project)
        else:
            # Generic pitch
            email = self.templates.cold_email_vc(target, self.project)
        
        self.log(f"Generated email for {target.name} ({target.target_type})")
        return email
    
    def batch_generate_emails(self, targets: List[PitchTarget], output_dir: Optional[Path] = None) -> Dict[str, str]:
        """Generate emails for multiple targets"""
        if output_dir is None:
            output_dir = Path("pitch_emails")
        
        output_dir.mkdir(exist_ok=True)
        
        emails = {}
        for target in targets:
            email_content = self.generate_email(target)
            
            # Save to file
            filename = f"{target.organization.lower().replace(' ', '_')}_{target.name.lower().replace(' ', '_')}.txt"
            filepath = output_dir / filename
            filepath.write_text(email_content)
            
            emails[target.email] = email_content
        
        self.log(f"Generated {len(emails)} pitch emails in {output_dir}")
        return emails
    
    def send_email(self, target: PitchTarget, email_content: str, 
                   smtp_config: Optional[Dict] = None, dry_run: bool = True) -> bool:
        """
        Send email via SMTP
        
        Args:
            target: PitchTarget with email address
            email_content: Email body text
            smtp_config: Dict with 'host', 'port', 'username', 'password'
            dry_run: If True, just logs without actually sending
        
        Returns:
            True if sent successfully (or dry_run), False otherwise
        """
        if dry_run:
            self.log(f"[DRY RUN] Would send email to {target.email}")
            print(f"\n--- Email Preview ---")
            print(email_content[:500] + "...")
            print(f"--- End Preview ---\n")
            return True
        
        if not smtp_config:
            self.log("SMTP config required for actual sending", level="ERROR")
            return False
        
        try:
            # Parse subject from email content
            subject_line = email_content.split('\n')[0].replace('Subject: ', '')
            body = '\n'.join(email_content.split('\n')[2:])
            
            msg = MIMEMultipart()
            msg['From'] = smtp_config['username']
            msg['To'] = target.email
            msg['Subject'] = subject_line
            
            msg.attach(MIMEText(body, 'plain'))
            
            server = smtplib.SMTP(smtp_config['host'], smtp_config['port'])
            server.starttls()
            server.login(smtp_config['username'], smtp_config['password'])
            
            server.send_message(msg)
            server.quit()
            
            self.log(f"Successfully sent email to {target.email}")
            return True
            
        except Exception as e:
            self.log(f"Failed to send email to {target.email}: {e}", level="ERROR")
            return False
    
    def create_pitch_package(self, targets: List[PitchTarget], output_dir: Optional[Path] = None):
        """
        Generate complete pitch package:
        - Investor deck
        - Grant proposal (if applicable)
        - Personalized emails for all targets
        """
        if output_dir is None:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            output_dir = Path(f"pitch_package_{timestamp}")
        
        output_dir.mkdir(exist_ok=True)
        
        self.log(f"Creating pitch package in {output_dir}")
        
        # Generate core documents
        deck_path = output_dir / "investor_deck.md"
        self.generate_investor_deck(deck_path)
        
        # Generate grant proposal if any grant targets
        if any(t.target_type == "grant" for t in targets):
            grant_path = output_dir / "grant_proposal.md"
            self.generate_grant_proposal(grant_path)
        
        # Generate personalized emails
        email_dir = output_dir / "emails"
        self.batch_generate_emails(targets, email_dir)
        
        # Generate tracking sheet
        tracking_data = {
            "package_created": datetime.now().isoformat(),
            "project": self.project.name,
            "targets": [
                {
                    "name": t.name,
                    "organization": t.organization,
                    "email": t.email,
                    "type": t.target_type,
                    "status": "pending"
                }
                for t in targets
            ]
        }
        
        tracking_path = output_dir / "outreach_tracker.json"
        tracking_path.write_text(json.dumps(tracking_data, indent=2))
        
        self.log(f"✅ Pitch package complete: {len(targets)} personalized emails ready")
        
        return output_dir
    
    def log(self, message: str, level: str = "INFO"):
        """Log to console and Pattern Journal"""
        timestamp = datetime.now().strftime("%H:%M:%S")
        emoji = {"INFO": "📧", "ERROR": "❌", "WARNING": "⚠️"}.get(level, "📝")
        print(f"{emoji} [{timestamp}] {message}")
        
        try:
            entry = {
                "timestamp": time.time(),
                "timestamp_human": datetime.now().isoformat(),
                "level": level,
                "module": "Syntax_AI_PitchGenerator",
                "message": message
            }
            
            with open(self.log_file, 'a', encoding='utf-8') as f:
                f.write(json.dumps(entry) + '\n')
        except Exception as e:
            print(f"⚠️  Failed to log to Pattern Journal: {e}")


